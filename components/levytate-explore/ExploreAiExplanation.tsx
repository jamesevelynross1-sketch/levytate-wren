"use client";

import { useEffect, useState } from "react";
import { RefreshCw, BookOpen, ExternalLink, ShieldCheck, Sparkles, WandSparkles } from "lucide-react";
import type { ExploreStandard } from "@/lib/levytate/explore/catalogue";
import { exploreNarrativeSchema, type ExploreNarrative } from "@/lib/levytate/explore/narrative";

type AiState = "loading" | "ready" | "error";
type ExplanationResponse = {
  state?: "generating" | "ready";
  retryAfterSeconds?: number;
  narrative?: ExploreNarrative;
  message?: string;
  code?: string;
  source?: { generatedAt?: string; cached?: boolean };
};

function friendlyDate(value: string | undefined) {
  if (!value) return null;
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? null
    : date.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
}

/**
 * A programme click mounts this component and begins a live, server-side
 * transformation. If a matching, already-generated source/version story is
 * cached, the same endpoint returns it instantly without spending AI tokens.
 * This is transparent in the UI; it never pretends static editorial was
 * just generated by AI.
 */
export function ExploreAiExplanation({ standard }: { standard: ExploreStandard }) {
  const [status, setStatus] = useState<AiState>("loading");
  const [narrative, setNarrative] = useState<ExploreNarrative | null>(null);
  const [failure, setFailure] = useState("");
  const [usedCache, setUsedCache] = useState(false);
  const [generatedAt, setGeneratedAt] = useState<string | undefined>();
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    const controller = new AbortController();
    let disposed = false;
    let pending: ReturnType<typeof setTimeout> | undefined;

    setStatus("loading");
    setNarrative(null);
    setFailure("");

    async function explain(retries: number) {
      try {
        const response = await fetch("/api/levytate-explore/de-fluff", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ code: standard.code }),
          signal: controller.signal,
          cache: "no-store",
        });
        const data = (await response.json()) as ExplanationResponse;
        if (disposed || controller.signal.aborted) return;

        if (response.status === 202 && data.state === "generating") {
          if (retries >= 12) throw new Error("This explanation is taking longer than expected. Please try again.");
          const pause = Math.max(2, Math.min(data.retryAfterSeconds || 3, 8)) * 1000;
          pending = setTimeout(() => void explain(retries + 1), pause);
          return;
        }

        if (!response.ok || data.state !== "ready") {
          throw new Error(data.message || "We couldn't generate a reliable explanation right now.");
        }

        const parsed = exploreNarrativeSchema.safeParse(data.narrative);
        if (!parsed.success) throw new Error("The explanation did not pass its content checks.");
        setNarrative(parsed.data);
        setGeneratedAt(data.source?.generatedAt);
        setUsedCache(data.source?.cached === true);
        setStatus("ready");
      } catch (error) {
        if (disposed || controller.signal.aborted) return;
        setStatus("error");
        setFailure(error instanceof Error ? error.message : "The AI explanation isn't available right now.");
      }
    }

    void explain(0);
    return () => {
      disposed = true;
      controller.abort();
      if (pending) clearTimeout(pending);
    };
  }, [standard.code, attempt]);

  return (
    <section aria-labelledby="unpacked-title" className="mt-8">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-[#142f3a]/15 pb-4">
        <h2 id="unpacked-title" className="explore-unpacked-heading flex items-center gap-2 text-[clamp(26px,3vw,33px)] font-extrabold">
          <WandSparkles size={23} className="text-[#126955]" aria-hidden="true" />
          Unpacked
        </h2>
        <span className="explore-soft-stamp text-[#142f3a]/75">AI explanation · not official advice</span>
      </div>

      {status === "loading" ? (
        <div role="status" aria-live="polite" className="explore-unpacked-hero mt-5 overflow-hidden border border-[#142f3a]/10 p-7 sm:p-9">
          <div className="flex items-start gap-3">
            <span className="grid h-11 w-11 shrink-0 animate-pulse place-items-center rounded-full bg-[#d9f3a1] text-[#142f3a] motion-reduce:animate-none">
              <Sparkles size={20} aria-hidden="true" />
            </span>
            <div>
              <h3 className="text-[23px] font-extrabold tracking-[-.045em]">Unpacking what this really means.</h3>
              <p className="mt-2 text-sm leading-7 text-[#102c3d]/65">
                Checking the source, finding the useful details and translating them into everyday language.
              </p>
            </div>
          </div>
          <div aria-hidden="true" className="mt-8 space-y-3">
            <div className="h-3 w-[88%] animate-pulse rounded-full bg-[#cadfb0] motion-reduce:animate-none" />
            <div className="h-3 w-[76%] animate-pulse rounded-full bg-[#cadfb0] motion-reduce:animate-none" />
            <div className="h-3 w-[63%] animate-pulse rounded-full bg-[#cadfb0] motion-reduce:animate-none" />
          </div>
        </div>
      ) : null}

      {status === "error" ? (
        <div role="status" className="mt-5 rounded-[23px] border border-[#142f3a]/10 bg-[#fff0e4] p-7 sm:p-9">
          <div className="flex items-start gap-3">
            <ShieldCheck size={23} className="mt-0.5 shrink-0 text-[#117f70]" aria-hidden="true" />
            <div>
              <h3 className="text-[21px] font-semibold tracking-[-.04em]">Unpacked isn&apos;t available yet.</h3>
              <p className="mt-3 text-sm leading-7 text-[#102c3d]/65">
                {failure} We won&apos;t guess what an apprenticeship teaches when we cannot verify the official information.
              </p>
              <div className="mt-5 flex flex-wrap gap-3">
                <button type="button" onClick={() => setAttempt(value => value + 1)}
                  className="inline-flex min-h-[45px] items-center gap-2 rounded-full bg-[#102c3d] px-5 text-xs font-semibold text-white transition hover:bg-[#214957]">
                  <RefreshCw size={15} aria-hidden="true" /> Try again
                </button>
                <a href={standard.officialUrl} target="_blank" rel="noopener noreferrer"
                  className="inline-flex min-h-[45px] items-center gap-2 rounded-full border border-[#102c3d]/20 px-5 text-xs font-semibold">
                  <BookOpen size={15} aria-hidden="true" /> Official standard <ExternalLink size={13} aria-hidden="true" />
                </a>
              </div>
            </div>
          </div>
        </div>
      ) : null}

      {status === "ready" && narrative ? (
        <div aria-live="polite" className="mt-5">
          <div className="explore-unpacked-hero px-6 pb-7 pt-7 sm:px-9 sm:pb-10 sm:pt-9">
            <p className="text-[11px] font-bold uppercase tracking-[.16em] text-[#117f70]">
              {usedCache ? "Previously unpacked from the official source" : "Unpacked by AI from the official source"}
            </p>
            <h3 className="mt-5 max-w-[700px] font-serif text-[clamp(2rem,4.4vw,3.35rem)] leading-[1.1] tracking-[-.055em] text-[#142f3a]">{narrative.headline}</h3>
            <p className="mt-5 whitespace-pre-wrap text-[15px] leading-[1.85] text-[#142f3a]/82 sm:text-[16px]">{narrative.introduction}</p>
          </div>

          <div className="mt-9">
            <h3 className="text-[23px] font-extrabold tracking-[-.045em]">What would you actually learn?</h3>
            <ul className="mt-4 space-y-3">
              {narrative.whatYouWillLearn.map((point, index) => (
                <li key={index} className="flex items-start gap-4 rounded-[15px] border border-[#142f3a]/10 bg-white p-5">
                  <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-[#fdd2c2] text-xs font-extrabold text-[#142f3a]">0{index + 1}</span>
                  <span className="text-sm leading-7 text-[#102c3d]/78">{point}</span>
                </li>
              ))}
            </ul>
          </div>

          <div className="mt-9">
            <h3 className="text-xl font-semibold tracking-[-.035em]">What could that look like at work?</h3>
            <ul className="mt-4 grid gap-3">
              {narrative.whatThisCouldLookLikeAtWork.map((point, index) => (
                <li key={index} className="flex gap-3 rounded-[16px] bg-[#ebe5ff] p-5 text-sm leading-7 text-[#142f3a]/80">
                  <Sparkles size={18} className="mt-1 shrink-0 text-[#a54b61]" aria-hidden="true" />
                  {point}
                </li>
              ))}
            </ul>
          </div>

          <div className="mt-8 grid gap-4 md:grid-cols-2">
            <div className="rounded-[18px] border border-[#102c3d]/10 bg-white p-6">
              <h3 className="text-lg font-semibold tracking-[-.035em]">Could this be for you?</h3>
              <p className="mt-3 text-sm leading-7 text-[#102c3d]/68">{narrative.whoItMightSuit}</p>
            </div>
            <div className="rounded-[18px] border border-[#102c3d]/10 bg-white p-6">
              <h3 className="text-lg font-semibold tracking-[-.035em]">What should you know first?</h3>
              <p className="mt-3 text-sm leading-7 text-[#102c3d]/68">{narrative.whatToKnowBeforeYouStart}</p>
            </div>
          </div>
          <div className="mt-6 rounded-[17px] border-l-[6px] border-[#276a58] bg-[#e4f1d0] p-5">
            <p className="text-xs font-bold uppercase tracking-[.12em] text-[#117f70]">A good question for your manager</p>
            <p className="mt-2 text-[15px] leading-7 text-[#102c3d]/85">{narrative.aConversationStarter}</p>
          </div>
          <p className="mt-5 text-xs leading-6 text-[#102c3d]/55">
            This is an AI-generated interpretation, not an official syllabus or eligibility assessment. It was based on linked Skills England occupational evidence{friendlyDate(generatedAt) ? ", processed " + friendlyDate(generatedAt) : ""}. Please check the official standard for the complete requirements.
          </p>
        </div>
      ) : null}

      <details className="mt-7 rounded-[16px] border border-[#142f3a]/15 bg-white p-5 sm:p-6">
        <summary className="cursor-pointer min-h-[35px] text-[14px] font-extrabold text-[#142f3a]">View original apprenticeship details</summary>
        <dl className="mt-4 divide-y divide-[#102c3d]/10 text-sm">
          {[
            ["Standard", standard.title],
            ["Reference", standard.code],
            ["Level", String(standard.level)],
            ["Typical duration", standard.duration],
            ["Version", standard.version],
            ["Catalogue last verified", standard.sourceVerified || "Not recorded"],
          ].map(([key, value]) => (
            <div key={key} className="grid grid-cols-[130px_1fr] gap-3 py-3">
              <dt className="text-[#102c3d]/50">{key}</dt>
              <dd className="font-medium">{value}</dd>
            </div>
          ))}
        </dl>
        <a href={standard.officialUrl} target="_blank" rel="noopener noreferrer" className="mt-4 inline-flex items-center gap-2 text-sm font-semibold text-[#117f70] underline underline-offset-2">Read the full official source <ExternalLink size={15} aria-hidden="true" /></a>
      </details>
    </section>
  );
}
