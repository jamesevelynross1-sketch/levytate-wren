const now = "2026-06-29";
const national = ["England", "Remote", "Hybrid"];

function programme(
  providerId: string,
  standardId: string,
  deliveryMode: string,
  regions: string[],
  sourceUrl: string,
  verificationStatus: ProviderProgrammeVerificationStatus,
  notes = "",
  status: ProviderProgramme["status"] = verificationStatus === "Needs manual verification" ? "Needs verification" : "Active",
): ProviderProgramme {
  return {
    id: `${providerId}-${standardId.toLowerCase()}`,
    providerId,
    apprenticeshipStandardId: standardId,
    deliveryMode,
    regions,
    status,
    verificationStatus,
    sourceUrl,
    notes,
    recordStatus: "Active",
    createdAt: now,
    updatedAt: now,
  };
}

