import type { ProviderCatalogueRecord, ProviderProgramme } from "@/lib/levytate/domain";

const today = "2026-06-25";
const national = ["England", "Remote", "Hybrid"];
type ProgrammeSeed = [string, string, string, string, string, string, string[], ProviderProgramme["verificationStatus"]?, ProviderProgramme["fundingStatus"]?, boolean?];

function p(providerId: string, website: string, seed: ProgrammeSeed): ProviderProgramme {
  const [slug, programmeName, level, standardName, sector, deliveryMode, tags, verificationStatus = "verified", fundingStatus = "potentially_levy_or_co_investment", availableForNewRecommendations = true] = seed;
  return {
    programmeId: `${providerId}-${slug}`,
    programmeName,
    level,
    standardName,
    sector,
    deliveryMode,
    typicalDuration: level === "Commercial" || level === "Category" ? "Programme dependent" : "12 to 36 months, subject to standard",
    fundingStatus,
    availableForNewRecommendations,
    suitableRoles: tags,
    tags,
    sourceUrl: website,
    verificationStatus,
  };
}

function provider(input: Omit<ProviderCatalogueRecord, "lastVerified" | "programmes"> & { programmes: ProgrammeSeed[] }): ProviderCatalogueRecord {
  return {
    ...input,
    lastVerified: today,
    programmes: input.programmes.map((programme) => p(input.providerId, input.website, programme)),
  };
}

