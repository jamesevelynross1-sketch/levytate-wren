function programme(config: {
  id: string;
  providerId: string;
  programmeName: string;
  shortDescription: string;
  fullDescription?: string;
  targetOrganisations?: string[];
  targetIndustries: string[];
  targetJobRoles: string[];
  seniority?: ProviderProgrammeSeniority;
  employerSize?: ProviderEmployerSize;
  businessProblemsSolved: string[];
  skillsDeveloped: string[];
  technologiesCovered: string[];
  expectedOutcomes: string[];
  deliveryModels: string[];
  regions?: string[];
  duration: string;
  cohortOptions?: string[];
  commercialNotes?: string;
  fundingRoute?: FundingRoute;
  linkedStandardIds: string[];
  sourceUrl: string;
  verificationStatus: ProviderProgrammeVerificationStatus;
  notes?: string;
  status?: ProviderProgramme["status"];
}): ProviderProgramme {
  return {
    id: config.id,
    providerId: config.providerId,
    programmeName: config.programmeName,
    shortDescription: config.shortDescription,
    fullDescription: config.fullDescription ?? config.shortDescription,
    status: config.status ?? (config.verificationStatus === "Needs manual verification" ? "Needs verification" : "Active"),
    verificationStatus: config.verificationStatus,
    targetOrganisations: config.targetOrganisations ?? ["Employers improving workforce capability", "Multi-site organisations"],
    targetIndustries: config.targetIndustries,
    targetJobRoles: config.targetJobRoles,
    seniority: config.seniority ?? "Mixed",
    employerSize: config.employerSize ?? "Mixed employer base",
    businessProblemsSolved: config.businessProblemsSolved,
    skillsDeveloped: config.skillsDeveloped,
    technologiesCovered: config.technologiesCovered,
    expectedOutcomes: config.expectedOutcomes,
    deliveryModels: config.deliveryModels,
    regions: config.regions ?? national,
    duration: config.duration,
    cohortOptions: config.cohortOptions ?? ["Open cohorts", "Employer cohorts"],
    commercialNotes: config.commercialNotes ?? "Commercial terms confirmed during controlled LevyTate matching.",
    fundingRoute: config.fundingRoute ?? "Potentially funded through levy/co-investment",
    linkedStandardId: config.linkedStandardIds[0] ?? "",
    linkedStandardIds: config.linkedStandardIds,
    linkedStandardName: "",
    level: null,
    route: "",
    fundingBand: null,
    officialUrl: "",
    sourceUrl: config.sourceUrl,
    notes: config.notes ?? "",
    recordStatus: "Active",
    createdAt: now,
    updatedAt: now,
  };
}

